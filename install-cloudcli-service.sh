#!/usr/bin/env bash
set -euo pipefail
source "$(dirname "${BASH_SOURCE[0]}")/lib.sh"

usage() {
  cat <<USAGE
Usage: ./install-cloudcli-service.sh [--restart] [-y]

Install CloudCLI as a systemd user service, so it starts on boot and is
restarted if it crashes. Re-run it after upgrading node/nvm or changing .env.
Docker Compose services already restart on boot on their own.

A CloudCLI already started by start.sh is left running; the service takes
over on the next boot.

Options:
  --restart      switch a running CloudCLI over to the service now (drops
                 live terminal sessions, asks first)
  -y, --yes      don't ask (required with --restart when not run from a
                 terminal)
USAGE
}

RESTART=false
ASSUME_YES=false
for arg in "$@"; do
  case "$arg" in
    -h|--help) usage; exit 0 ;;
    --restart) RESTART=true ;;
    -y|--yes) ASSUME_YES=true ;;
    *) die_usage "Unknown option: $arg" ;;
  esac
done

load_env

REPO_DIR="$(pwd -P)"
UNIT_DIR="${XDG_CONFIG_HOME:-$HOME/.config}/systemd/user"
UNIT_FILE="$UNIT_DIR/$CLOUDCLI_SERVICE"

# systemd doesn't load the shell profile, so nvm's node isn't on PATH there.
# Pin the absolute binary and the current PATH (cloudcli spawns node, claude, etc.).
CLOUDCLI_BIN="$(command -v cloudcli || true)"
if [ -z "$CLOUDCLI_BIN" ]; then
  die "cloudcli is not on PATH, install it first: npm install -g @cloudcli-ai/cloudcli"
fi

if [ "$RESTART" = true ]; then
  confirm_cloudcli restart
fi

mkdir -p "$CLOUDCLI_DATA_DIR" "$UNIT_DIR"

if [ ! -f "$CLOUDCLI_ENV_FILE" ]; then
  warn "$CLOUDCLI_ENV_FILE not found, CloudCLI starts without it"
  hint "put KEY=value lines there (e.g. ANTHROPIC_* for claude), then ./restart.sh cloudcli"
elif [ "$(stat -c %a "$CLOUDCLI_ENV_FILE")" != 600 ]; then
  warn "$CLOUDCLI_ENV_FILE is readable by others, it may hold credentials"
  hint "chmod 600 $CLOUDCLI_ENV_FILE"
fi

cat >"$UNIT_FILE" <<UNIT
# Generated by $REPO_DIR/install-cloudcli-service.sh, re-run it to regenerate.
[Unit]
Description=CloudCLI (claude-code-ui) on port $CLOUDCLI_PORT
After=network-online.target
Wants=network-online.target

[Service]
Type=simple
WorkingDirectory=$REPO_DIR
Environment="PATH=$PATH"
Environment=SERVER_PORT=$CLOUDCLI_PORT
Environment="DATABASE_PATH=$DBFILE"
Environment=IS_PLATFORM=true
Environment=VITE_IS_PLATFORM=true
# Optional ("-"): extra env (e.g. claude credentials), read at every start.
EnvironmentFile=-$CLOUDCLI_ENV_FILE
ExecStartPre=/bin/bash -c 'source "$LIB_FILE" && load_env && rotate_cloudcli_log'
ExecStart=$CLOUDCLI_BIN
# Keep the pid file that start.sh, stop.sh and status.sh rely on.
ExecStartPost=/bin/sh -c 'echo \$MAINPID > "$PIDFILE"'
ExecStopPost=/bin/rm -f "$PIDFILE"
StandardOutput=append:$LOGFILE
StandardError=append:$LOGFILE
Restart=on-failure
RestartSec=5

[Install]
WantedBy=default.target
UNIT
ok "wrote $UNIT_FILE"

systemctl --user daemon-reload
systemctl --user enable --quiet "$CLOUDCLI_SERVICE"
ok "$CLOUDCLI_SERVICE enabled (starts on boot)"

# Without linger, user services only run while the user is logged in.
if [ "$(loginctl show-user "$USER" -p Linger --value 2>/dev/null)" = yes ] \
  || loginctl enable-linger "$USER" 2>/dev/null; then
  ok "linger enabled for $USER (runs at boot without a login)"
else
  warn "could not enable linger, so the service only runs while you're logged in"
  hint "sudo loginctl enable-linger $USER"
fi

if [ "$RESTART" = true ]; then
  cloudcli_restart
elif PID="$(cloudcli_pid)" && ! cloudcli_service_active; then
  ok "cloudcli: left running outside the service (pid $PID); the service takes over on the next boot"
  hint "./restart.sh cloudcli to switch now (drops live terminal sessions)"
else
  cloudcli_start
fi
