#!/usr/bin/env bash
set -euo pipefail
cd "$(dirname "${BASH_SOURCE[0]}")"

# Installs CloudCLI as a systemd user service so it starts on boot and is
# restarted if it crashes. Docker Compose services already come back on their
# own (restart: unless-stopped).

RESTART=false
for arg in "$@"; do
  case "$arg" in
    --restart) RESTART=true ;;
    *) echo "Unknown option: $arg" >&2; exit 1 ;;
  esac
done

if [ ! -f ".env" ] || [ ! -r ".env" ]; then
  echo ".env file is missing or not readable" >&2
  exit 1
fi

set -a
source .env
set +a

# Keep in sync with start.sh, docker-compose.yml and status.sh.
CLOUDCLI_PORT=3010
SERVICE_NAME=cloudcli.service

REPO_DIR="$(pwd -P)"
DATA_DIR="$(realpath -m "$CLOUDCLI_DATA_DIR")"
PIDFILE="$DATA_DIR/cloudcli.pid"
LOGFILE="$DATA_DIR/cloudcli.log"
DBFILE="$DATA_DIR/auth.db"
UNIT_DIR="${XDG_CONFIG_HOME:-$HOME/.config}/systemd/user"
UNIT_FILE="$UNIT_DIR/$SERVICE_NAME"

# systemd doesn't load the shell profile, so nvm's node isn't on PATH there.
# Pin the absolute binary and the current PATH (cloudcli spawns node, claude, etc.).
CLOUDCLI_BIN="$(command -v cloudcli || true)"
if [ -z "$CLOUDCLI_BIN" ]; then
  echo "cloudcli is not on PATH, install it first: npm install -g @cloudcli-ai/cloudcli" >&2
  exit 1
fi

mkdir -p "$DATA_DIR" "$UNIT_DIR"

echo "Writing $UNIT_FILE..."
cat >"$UNIT_FILE" <<EOF
# Generated by $REPO_DIR/install-cloudcli-service.sh, re-run it to regenerate.
[Unit]
Description=CloudCLI (claude-code-ui) on port $CLOUDCLI_PORT
After=network-online.target
Wants=network-online.target

[Service]
Type=simple
WorkingDirectory=$REPO_DIR
Environment="PATH=$PATH"
Environment=SERVER_PORT=$CLOUDCLI_PORT
Environment="DATABASE_PATH=$DBFILE"
Environment=IS_PLATFORM=true
Environment=VITE_IS_PLATFORM=true
ExecStart=$CLOUDCLI_BIN
# Keep the pid file that start.sh, stop.sh and status.sh rely on.
ExecStartPost=/bin/sh -c 'echo \$MAINPID > "$PIDFILE"'
ExecStopPost=/bin/rm -f "$PIDFILE"
StandardOutput=append:$LOGFILE
StandardError=append:$LOGFILE
Restart=on-failure
RestartSec=5

[Install]
WantedBy=default.target
EOF

systemctl --user daemon-reload
systemctl --user enable "$SERVICE_NAME"

# Without linger, user services only run while the user is logged in.
if [ "$(loginctl show-user "$USER" -p Linger --value 2>/dev/null)" != yes ]; then
  if ! loginctl enable-linger "$USER" 2>/dev/null; then
    echo
    echo "Could not enable linger. Run this once so cloudcli starts at boot:" >&2
    echo "  sudo loginctl enable-linger $USER" >&2
  fi
fi

# A cloudcli started by start.sh holds the port; replacing it drops every live
# terminal session, so only do that when explicitly asked to.
if systemctl --user is-active --quiet "$SERVICE_NAME"; then
  if [ "$RESTART" = true ]; then
    echo "Restarting $SERVICE_NAME..."
    systemctl --user restart "$SERVICE_NAME"
  else
    echo "$SERVICE_NAME already running."
  fi
elif [ -f "$PIDFILE" ] && kill -0 "$(cat "$PIDFILE")" 2>/dev/null; then
  if [ "$RESTART" = false ]; then
    echo
    echo "cloudcli is already running outside the service (pid $(cat "$PIDFILE")), leaving it alone."
    echo "The service will take over on next boot, or re-run with --restart to switch now"
    echo "(this drops live terminal sessions)."
    exit 0
  fi
  OLD_PID="$(cat "$PIDFILE")"
  echo "Stopping cloudcli (pid $OLD_PID)..."
  kill "$OLD_PID"
  for _ in $(seq 1 10); do
    kill -0 "$OLD_PID" 2>/dev/null || break
    sleep 1
  done
  kill -9 "$OLD_PID" 2>/dev/null || true
  rm -f "$PIDFILE"
  echo "Starting $SERVICE_NAME..."
  systemctl --user start "$SERVICE_NAME"
else
  echo "Starting $SERVICE_NAME..."
  systemctl --user start "$SERVICE_NAME"
fi

echo "Waiting for cloudcli to become healthy..."
for _ in $(seq 1 30); do
  curl -sf "http://127.0.0.1:$CLOUDCLI_PORT/health" >/dev/null 2>&1 && break
  sleep 1
done
curl -sf "http://127.0.0.1:$CLOUDCLI_PORT/health" >/dev/null 2>&1 || {
  echo "cloudcli did not become healthy, see $LOGFILE and: systemctl --user status $SERVICE_NAME" >&2
  exit 1
}

echo "Done."
